/**
 * 플레이어가 바라보는 네 방향. 화면 좌표 기준이라 `front`는 카메라를 향한 정면,
 * `back`은 화면 위쪽으로 걸어가는 뒷모습이다.
 */
export type Facing = 'front' | 'back' | 'left' | 'right';

/**
 * 이동 방향 벡터에서 바라볼 방향을 고른다.
 *
 * 원천은 실제 변위가 아니라 이동 **입력 의도**다. 호출부(`PlayerController`)는 장애물 해소와
 * 아레나 클램프를 거쳐 위치를 정하므로, 벽을 밀고 있으면 입력이 있어도 변위가 0에 가까워진다.
 * 변위로 방향을 뽑으면 벽에 닿는 순간 바라보던 방향을 잃어 캐릭터가 튄다.
 *
 * @param x 이동 방향의 가로 성분. 양수면 오른쪽
 * @param y 이동 방향의 세로 성분. 양수면 화면 위쪽
 * @param prev 직전에 바라보던 방향. 입력이 0이면 이 값을 그대로 돌려준다
 * @returns 네 방향 중 하나
 */
export function facingFromMoveDir(x: number, y: number, prev: Facing): Facing {
  // 입력이 없으면 직전 방향을 유지한다. 멈출 때마다 정면으로 되돌리면 걷다 서는 매 순간
  // 캐릭터가 홱 돌아본다.
  if (x === 0 && y === 0) return prev;
  // 대각선 입력은 호출부에서 정규화되면 |x|와 |y|가 정확히 같은 값(1/√2)이 되어 우세 축이
  // 사라진다. 동률에 결정적 규칙을 두지 않으면 어느 쪽이 이기는지가 부동소수 비교에 맡겨져
  // 좌우와 상하가 프레임마다 흔들린다. 마법사는 모자·지팡이 옆모습이 정면·후면보다 잘 읽히므로
  // 동률이면 가로를 택한다 — 그래서 `>=`로 가로가 이긴다.
  if (Math.abs(x) >= Math.abs(y)) return x > 0 ? 'right' : 'left';
  return y > 0 ? 'back' : 'front';
}
